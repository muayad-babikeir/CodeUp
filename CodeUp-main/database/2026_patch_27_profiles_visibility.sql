-- Patch 27: صلاحية قراءة أوسع لجدول profiles
-- تم تطبيقه مباشرة على قاعدة الإنتاج بتاريخ 2026-08-29.
-- السبب: سياسة القراءة القديمة كانت تسمح للمستخدم يشوف صفّه هو بس (أو سوبر أدمن) —
-- وهذا كان يكسر بصمت: البحث عن أشخاص، نافذة "محادثة جديدة"، وأسماء المستخدمين
-- الأخرى بالتايم لاين/التعليقات/لوحة المتصدرين (أي embed لـ profiles(full_name) لغير صاحب الحساب).
-- الإصلاح: أي مستخدم موثّق يقدر يشوف أي صف بجدول profiles — لكن الكود نفسه (index.html)
-- لا يطلب عمود email إلا لصاحب الحساب نفسه، حماية إضافية على مستوى الاستعلام مو بس RLS.

drop policy if exists "profiles: يشوف نفسه أو سوبر أدمن يشوف ا" on profiles;
create policy "profiles: أي مستخدم موثّق يشوف الأسماء الأساسية" on profiles
  for select using (auth.uid() is not null);
